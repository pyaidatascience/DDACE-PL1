#include <stdio.h>

int main() {
    // Printing double quotes and backslashes inside a string
    printf("She said, \"C is powerful!\"\n");
    printf("File path: C:\\Users\\Admin\\file.c\n");

    // Printing a single quote character
    char quote = '\'';
    printf("Single quote character: %c\n", quote);

    // Printing a literal question mark
    printf("Are you sure\?\n");

    return 0;
}
